"""Evaluation sets on disk: per-set manifests, provenance records and eval/data/SOURCES.md.

Layout (all under eval/data/, git-ignored):

    <set>/manifest.jsonl   one utterance per line: id, audio, text, lang, mixed, duration_s, sha256
    <set>/source.json      where the files came from: URLs, revision, licence, per-file SHA-256
    <set>/audio/*.wav      16 kHz mono PCM16
    SOURCES.md             regenerated from every source.json
"""

from __future__ import annotations

import datetime as dt
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

from .common import DATA_DIR, sha256_bytes


@dataclass
class Utterance:
    id: str
    audio: str  # path relative to the set folder
    text: str  # reference transcript as published (normalised only at scoring time)
    lang: str  # expected language: en, hi or ur
    mixed: bool  # reference mixes scripts (code-switched)
    duration_s: float
    sha256: str

    def wav_path(self, set_dir: Path) -> Path:
        return set_dir / self.audio


@dataclass
class SourceFile:
    name: str
    url: str
    bytes: int
    sha256: str


@dataclass
class Source:
    set: str
    title: str
    url: str  # dataset page
    revision: str  # repository commit the files were taken from
    licence: str  # as published by the source
    licence_evidence: str  # where the licence was read
    terms: str  # how STELMAR may use it
    files: list[SourceFile] = field(default_factory=list)
    utterances: int = 0
    hours: float = 0.0
    manifest_sha256: str = ""
    prepared_at: str = ""
    notes: str = ""


def set_dir(name: str) -> Path:
    return DATA_DIR / name  # read at call time so tests can redirect it


def load_manifest(name: str, data_dir: Path | None = None) -> list[Utterance]:
    path = (data_dir or DATA_DIR) / name / "manifest.jsonl"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found; run eval/get_data.py {name} first")
    with path.open(encoding="utf-8") as f:
        return [Utterance(**json.loads(line)) for line in f if line.strip()]


def write_manifest(name: str, utterances: list[Utterance]) -> str:
    """Write manifest.jsonl sorted by id and return its SHA-256."""
    utterances = sorted(utterances, key=lambda u: u.id)
    body = "".join(json.dumps(asdict(u), ensure_ascii=False) + "\n" for u in utterances).encode("utf-8")
    path = set_dir(name) / "manifest.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(body)
    return sha256_bytes(body)


def write_source(src: Source, utterances: list[Utterance]) -> None:
    src.utterances = len(utterances)
    src.hours = round(sum(u.duration_s for u in utterances) / 3600, 3)
    src.manifest_sha256 = write_manifest(src.set, utterances)
    src.prepared_at = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    (set_dir(src.set) / "source.json").write_text(
        json.dumps(asdict(src), ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    write_sources_md()


def read_sources(data_dir: Path | None = None) -> list[Source]:
    out = []
    for path in sorted((data_dir or DATA_DIR).glob("*/source.json")):
        raw = json.loads(path.read_text(encoding="utf-8"))
        raw["files"] = [SourceFile(**f) for f in raw.get("files", [])]
        out.append(Source(**raw))
    return out


def write_sources_md(data_dir: Path | None = None) -> Path:
    data_dir = data_dir or DATA_DIR
    sources = read_sources(data_dir)
    lines = [
        "# Evaluation data sources",
        "",
        "Generated by `eval/get_data.py` from each set's `source.json`. Everything under `eval/data/` is",
        "git-ignored and is never committed or bundled. Audio is resampled to 16 kHz mono PCM16 WAV.",
        "",
        "| Set | Utterances | Hours | Licence | Terms | Source | Revision | Manifest SHA-256 | Prepared |",
        "| --- | ---: | ---: | --- | --- | --- | --- | --- | --- |",
    ]
    for s in sources:
        lines.append(
            f"| {s.set} | {s.utterances} | {s.hours:.2f} | {s.licence} | {s.terms} | {s.url} | "
            f"`{s.revision[:12]}` | `{s.manifest_sha256}` | {s.prepared_at} |"
        )
    for s in sources:
        lines += ["", f"## {s.set}: {s.title}", "", f"- Licence: {s.licence} ({s.licence_evidence})"]
        if s.notes:
            lines.append(f"- Notes: {s.notes}")
        lines += ["", "| Downloaded file | Bytes | SHA-256 |", "| --- | ---: | --- |"]
        lines += [f"| {f.url} | {f.bytes} | `{f.sha256}` |" for f in s.files]
    path = data_dir / "SOURCES.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
